export type ReportLanguage = 'en' | 'id';
export function reportLanguage(value: unknown): ReportLanguage {
  return value === 'id' ? 'id' : 'en';
}
export function reportTranslator(language: ReportLanguage) {
  return (
    text: string,
    values: Record<string, string | bigint | number> = {},
  ): string =>
    (reportCopy[language][text] ?? text).replace(
      /\{(\w+)\}/g,
      (placeholder, key: string) =>
        values[key] === undefined ? placeholder : String(values[key]),
    );
}
/** Local relative links preserve query state; language never enters report calculations. */
export function reportLanguageLinks(requestUrl: string) {
  const url = new URL(requestUrl, 'http://report.local');
  const link = (language: ReportLanguage) => {
    url.searchParams.set('lang', language);
    return `${url.pathname}${url.search}${url.hash}`;
  };
  return { en: link('en'), id: link('id') };
}
